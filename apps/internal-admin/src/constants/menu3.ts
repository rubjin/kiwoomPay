// 만든 화면의 경로. 없는 화면은 2depth 경로 + 3depth 번호(예: /transaction/integrated/02) → 준비 중 화면
const BUILT_PATHS: Record<string, string> = {
  KWPC040101: '/transaction/integrated/list',
  KWPC060102: '/settlement/merchant/execute',
  KWPC070101: '/operation/merchant-contract/basic/edit',
};

export const menu3Path = (menu: Menu3Info) =>
  BUILT_PATHS[menu.id] ?? `${MENU[menu.parent]}/${menu.id.slice(8)}`;

/** 경로가 속한 3depth 메뉴 (가장 길게 맞는 것) */
export function menu3OfPath(pathname: string): Menu3Info | undefined {
  return MENU3.map((m) => ({ m, path: menu3Path(m) }))
    .filter(({ path }) => pathname === path || pathname.startsWith(path + '/'))
    .sort((a, b) => b.path.length - a.path.length)[0]?.m;
}

/** 2depth 아래 3depth 메뉴 */
export const menu3Of = (parent: string) => MENU3.filter((m) => m.parent === parent);
