export interface ScreenInfo {
  system: SystemId;
  /** 화면ID */
  id: string;
  depth1: string;
  depth2: string;
  depth3: string;
  /** 화면명 (Figma 화면 제목) */
  name: string;
  /** 앱 안 경로 (시스템 url 뒤에 붙는다) */
  path: string;
  type: ScreenType;
  /** 적용한 페이지 패턴 (docs/ai/page-patterns-plan.md) */
  pattern?: string;
  status: ScreenStatus;
  /** 기획 반영 버전 (IA) */
  planVersion: string;
  /** 최종 업데이트일 YYYY-MM-DD */
  updatedAt: string;
  /** 시안 · 정책 없이 임시로 만든 부분 → "기타" 칸에 "임의 작업: …" */
  tempWork?: string;
}

